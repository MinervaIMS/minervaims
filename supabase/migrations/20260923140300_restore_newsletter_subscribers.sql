--       sophiac..froehlich@studbocconi.it  (sophia.froehlich@studbocconi.it is restored;
--                                           an address with ".." cannot be delivered)
--
-- NO DUPLICATES. Addresses are stored lower-case and trimmed (the
-- normalize_newsletter_email trigger) and are unique, so an address that
-- is already subscribed is simply left as it is (ON CONFLICT DO NOTHING):
-- its date and source are not overwritten. Step 1 removes any duplicate
-- that differs only by case or spaces, should one exist; it keeps the
-- oldest subscription.
--
-- NOBODY WHO UNSUBSCRIBED IS ADDED BACK. An address on the suppression
-- list (unsubscribed, bounced or complained) is skipped.
--
-- Idempotent: a second run inserts nothing.
-- =====================================================================

-- 1. Any duplicate differing only by case or surrounding spaces.
DELETE FROM public.newsletter_subscribers n
 USING public.newsletter_subscribers keep
 WHERE lower(btrim(n.email)) = lower(btrim(keep.email))
   AND n.id <> keep.id
   AND (n.subscribed_at, n.id) > (keep.subscribed_at, keep.id);

-- ...and the one kept is stored the way every new address is.
UPDATE public.newsletter_subscribers
   SET email = lower(btrim(email))
 WHERE email <> lower(btrim(email));

